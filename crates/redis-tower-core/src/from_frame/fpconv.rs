// Redis's Grisu2 digit selection. Layout and d2string's integer fast path are
// handled by the caller. Generic shortest formatters can select boundary
// decimals that fpconv intentionally excludes.
//
// Ported from Redis 8.10.2 deps/fpconv/fpconv_dtoa.c and fpconv_powers.h:
// https://github.com/redis/redis/tree/8.10.2/deps/fpconv

#[derive(Clone, Copy)]
struct Fp {
    frac: u64,
    exp: i32,
}

const HIDDEN_BIT: u64 = 1 << 52;

impl Fp {
    fn from_double(d: f64) -> Self {
        let bits = d.to_bits();
        let frac = bits & (HIDDEN_BIT - 1);
        let exp = ((bits >> 52) & 0x7ff) as i32;
        if exp == 0 {
            Self { frac, exp: -1074 }
        } else {
            Self {
                frac: frac + HIDDEN_BIT,
                exp: exp - 1075,
            }
        }
    }

    fn normalized(mut self) -> Self {
        let shift = self.frac.leading_zeros();
        self.frac <<= shift;
        self.exp -= shift as i32;
        self
    }

    fn boundaries(self) -> (Self, Self) {
        let upper = Self {
            frac: (self.frac << 1) + 1,
            exp: self.exp - 1,
        }
        .normalized();
        let shift = if self.frac == HIDDEN_BIT { 2 } else { 1 };
        let mut lower = Self {
            frac: (self.frac << shift) - 1,
            exp: self.exp - shift,
        };
        lower.frac <<= lower.exp - upper.exp;
        lower.exp = upper.exp;
        (lower, upper)
    }

    fn multiply(self, other: Self) -> Self {
        let product = u128::from(self.frac) * u128::from(other.frac);
        // fpconv rounds the discarded low half upwards at the midpoint.
        let frac = (product >> 64) as u64 + ((product >> 63) & 1) as u64;
        Self {
            frac,
            exp: self.exp + other.exp + 64,
        }
    }
}

fn cached_power(exp: i32) -> (Fp, i32) {
    // Keep fpconv's exact approximation, rather than substituting LOG10_2.
    #[allow(clippy::approx_constant)]
    const ONE_LOG_TEN: f64 = 0.301_029_995_663_981_14;
    let approx = (f64::from(-(exp + 87)) * ONE_LOG_TEN) as i32;
    let mut index = ((approx + 348) / 8) as usize;
    loop {
        let (frac, binary_exp) = POWERS_TEN[index];
        let current = exp + binary_exp + 64;
        if current < -60 {
            index += 1;
        } else if current > -32 {
            index -= 1;
        } else {
            return (
                Fp {
                    frac,
                    exp: binary_exp,
                },
                -348 + index as i32 * 8,
            );
        }
    }
}

fn round_digit(digits: &mut [u8], delta: u64, mut rem: u64, kappa: u64, frac: u64) {
    while rem < frac
        && delta - rem >= kappa
        && (rem + kappa < frac || frac - rem > rem + kappa - frac)
    {
        let last = digits
            .last_mut()
            .expect("a nonzero digit has been generated");
        *last -= 1;
        rem += kappa;
    }
}

fn generate_digits(fp: Fp, lower: Fp, upper: Fp, mut last: i32) -> (String, i32) {
    let wfrac = upper.frac - fp.frac;
    let mut delta = upper.frac - lower.frac;
    let shift = -upper.exp;
    let one = 1_u64 << shift;
    let mut part1 = upper.frac >> shift;
    let mut part2 = upper.frac & (one - 1);
    let mut digits = [0_u8; 18];
    let mut len = 0;
    let mut kappa = 10;

    for power in (0..10).rev() {
        let div = 10_u64.pow(power);
        let digit = part1 / div;
        if digit != 0 || len != 0 {
            digits[len] = b'0' + digit as u8;
            len += 1;
        }
        part1 -= digit * div;
        kappa -= 1;
        let rem = (part1 << shift) + part2;
        if rem <= delta {
            last += kappa;
            round_digit(&mut digits[..len], delta, rem, div << shift, wfrac);
            return (
                String::from_utf8(digits[..len].to_vec()).expect("ASCII digits"),
                last,
            );
        }
    }

    let mut unit = 10_u64;
    loop {
        part2 *= 10;
        delta *= 10;
        kappa -= 1;
        let digit = part2 >> shift;
        if digit != 0 || len != 0 {
            digits[len] = b'0' + digit as u8;
            len += 1;
        }
        part2 &= one - 1;
        if part2 < delta {
            last += kappa;
            // Match C's unsigned multiplication, including its wrapping semantics.
            round_digit(
                &mut digits[..len],
                delta,
                part2,
                one,
                wfrac.wrapping_mul(unit),
            );
            return (
                String::from_utf8(digits[..len].to_vec()).expect("ASCII digits"),
                last,
            );
        }
        unit *= 10;
    }
}

/// Redis fpconv's decimal digits and the exponent of their last digit.
pub(super) fn digits(d: f64) -> (String, i32) {
    debug_assert!(d.is_finite() && d > 0.0);
    let fp = Fp::from_double(d);
    let (lower, upper) = fp.boundaries();
    let (power, k) = cached_power(upper.exp);
    let fp = fp.normalized().multiply(power);
    let mut upper = upper.multiply(power);
    let mut lower = lower.multiply(power);
    lower.frac += 1;
    upper.frac -= 1;
    generate_digits(fp, lower, upper, -k)
}

